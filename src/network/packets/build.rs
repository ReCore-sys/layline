use std::path::{Path, PathBuf};
use std::{env, fs};

fn rust_files(dir: &Path, files: &mut Vec<PathBuf>) {
    for entry in
        fs::read_dir(dir).unwrap_or_else(|e| panic!("failed reading {}: {e}", dir.display()))
    {
        let path = entry.unwrap().path();
        if path.is_dir() {
            rust_files(&path, files);
        } else if path.extension().is_some_and(|extension| extension == "rs") {
            files.push(path);
        }
    }
}

fn module_path(src: &Path, file: &Path) -> String {
    let relative = file.strip_prefix(src).unwrap().with_extension("");
    let mut parts: Vec<_> = relative
        .components()
        .map(|part| part.as_os_str().to_string_lossy().into_owned())
        .collect();
    if parts.last().is_some_and(|part| part == "mod") {
        parts.pop();
    }
    format!("crate::{}", parts.join("::"))
}

fn is_inbound_packet(attribute: &syn::Attribute) -> bool {
    if !attribute.path().is_ident("packet") {
        return false;
    }
    let mut inbound = false;
    let _ = attribute.parse_nested_meta(|meta| {
        if meta.path.is_ident("inbound") {
            inbound = true;
        } else if meta.path.is_ident("name") {
            meta.value()?.parse::<syn::LitStr>()?;
        }
        Ok(())
    });
    inbound
}

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let src = manifest_dir.join("src");
    let inbound = src.join("inbound");

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", inbound.display());

    let mut files = Vec::new();
    rust_files(&inbound, &mut files);
    files.sort();

    let mut registrations = String::new();
    for file in files {
        println!("cargo:rerun-if-changed={}", file.display());
        let source = fs::read_to_string(&file).unwrap();
        let syntax = syn::parse_file(&source)
            .unwrap_or_else(|e| panic!("failed parsing {}: {e}", file.display()));
        let module = module_path(&src, &file);

        for item in syntax.items {
            let syn::Item::Struct(item) = item else {
                continue;
            };
            if item.attrs.iter().any(is_inbound_packet) {
                registrations.push_str(&format!(
                    "    registry.add_decoder::<{module}::{}>();\n",
                    item.ident
                ));
            }
        }
    }

    let generated = format!(
        "// Autogenerated by build.rs, do not edit.\n\n\
         fn register_inbound<W: 'static, S: 'static>(registry: &mut Registry<W, S>) {{\n\
         {registrations}}}\n"
    );
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(out_dir.join("inbound.rs"), generated).unwrap();
}
